export const documentTemplatesRelations = relations(documentTemplates, ({ one, many }) => ({
  institution: one(institutions, {
    fields: [documentTemplates.institutionId],
    references: [institutions.id],
  }),
  requests: many(documentRequests),
  issued: many(issuedDocuments),
}));

export const documentRequestsRelations = relations(documentRequests, ({ one, many }) => ({
  institution: one(institutions, {
    fields: [documentRequests.institutionId],
    references: [institutions.id],
  }),
  template: one(documentTemplates, {
    fields: [documentRequests.templateId],
    references: [documentTemplates.id],
  }),
  issued: many(issuedDocuments),
}));

export const issuedDocumentsRelations = relations(issuedDocuments, ({ one, many }) => ({
  institution: one(institutions, {
    fields: [issuedDocuments.institutionId],
    references: [institutions.id],
  }),
  request: one(documentRequests, {
    fields: [issuedDocuments.requestId],
    references: [documentRequests.id],
  }),
  template: one(documentTemplates, {
    fields: [issuedDocuments.templateId],
    references: [documentTemplates.id],
  }),
  verifications: many(documentVerifications),
}));

export const documentVerificationsRelations = relations(documentVerifications, ({ one }) => ({
  issuedDocument: one(issuedDocuments, {
    fields: [documentVerifications.issuedDocumentId],
    references: [issuedDocuments.id],
  }),
}));
